#!/usr/bin/env bash
# Prints CHANGELOG.md's section for a release, its heading included: the launcher updater's notes
# for it (latest.json's notes). The release steps write the section with git-cliff and commit it
# before the tag (docs/development.md), so the release workflow reads it from the tag's tree, and no
# git-cliff runs in a release (the hosting spec's Amendment D, HD2). The section is the same text
# `git cliff --latest --strip all` gives on the tag, but for blank lines at its end.
#   scripts/release-notes.sh VERSION [CHANGELOG]
# VERSION is the tag's, without its v (0.5.4, or 0.5.4-rc.1); CHANGELOG is CHANGELOG.md by default.
# Exits 1, printing nothing, when the changelog has no section for VERSION.
set -euo pipefail
export LC_ALL=C

fail() {
  echo "release-notes.sh: $1" >&2
  exit "${2:-1}"
}

if [ $# -lt 1 ] || [ $# -gt 2 ]; then
  echo "usage: $0 VERSION [CHANGELOG]" >&2
  exit 2
fi
version=$1 changelog=${2:-CHANGELOG.md}
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] ||
  fail "'$version' isn't a version such as 0.5.4 or 0.5.4-rc.1 (no v)" 2
[ -f "$changelog" ] || fail "no changelog at $changelog" 2

# From the section's heading, "## [VERSION] - DATE", to the next section's, or git-cliff's footer.
notes=$(awk -v head="## [$version] " '
  index($0, head) == 1 { on = 1; print; next }
  on && (/^## \[/ || /^<!-- generated by git-cliff -->/) { exit }
  on { print }
' "$changelog")
[ -n "$notes" ] ||
  fail "$changelog has no section for $version: write it with git cliff --tag v$version -o CHANGELOG.md, and commit it before the tag"
printf '%s\n' "$notes"
